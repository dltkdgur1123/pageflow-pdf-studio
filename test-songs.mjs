import assert from 'node:assert/strict';
import fs from 'node:fs';
import * as lib from 'pdf-lib';
import {createSongbook,collectSongPages} from './dist/songbook.mjs';
import {buildPDF} from './dist/core.mjs';
const sample=await createSongbook(lib);
assert.equal((await lib.PDFDocument.load(sample.bytes)).getPageCount(),8);
const groups=sample.songs.map(s=>({...s,pages:s.indexes.map(index=>({source:'book',index,rotation:0}))}));
const chosen=collectSongPages(groups);
assert.equal(groups.filter(s=>s.chosen).length,4);
assert.deepEqual(chosen.map(p=>p.index),[0,2,3,4,6,7]);
const original=Buffer.from(sample.bytes);
const bytes=await buildPDF(lib,new Map([['book',{bytes:sample.bytes}]]),chosen);
assert.equal((await lib.PDFDocument.load(bytes)).getPageCount(),6);
assert.deepEqual(Buffer.from(sample.bytes),original);
assert.deepEqual(collectSongPages([...groups].reverse()).map(p=>p.index),[6,7,4,2,3,0]);
assert.deepEqual(collectSongPages(groups.map(s=>({...s,chosen:false}))),[]);
fs.mkdirSync('test-results',{recursive:true});
fs.writeFileSync('test-results/songbook.pdf',sample.bytes);fs.writeFileSync('test-results/four-songs.pdf',bytes);
console.log('PASS: 6 songs / 8 source pages; 4 chosen songs / 6 output pages; expected page references, song reordering, empty selection, source immutability.');
